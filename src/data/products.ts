export function getProductBySlug(slug: string) {
  return products.find((p) => p.slug === slug);
}

export function getRelated(product: Product, limit = 4) {
  return products.filter((p) => p.id !== product.id && (p.category === product.category || p.featured)).slice(0, limit);
}

export function searchProducts(query: string) {
  const q = query.toLowerCase().trim();
  if (!q) return products;
  return products.filter((p) => {
    const hay = [p.name, p.nameHi, p.description, p.category, ...p.tags, ...p.colors].join(" ").toLowerCase();
    return q.split(/\s+/).every((word) => hay.includes(word));
  });
}

